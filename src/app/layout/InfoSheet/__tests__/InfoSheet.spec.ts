import { afterEach, describe, expect, it } from 'vitest';
import { mount } from '@vue/test-utils';
import type { VueWrapper } from '@vue/test-utils';
import InfoSheet from '../InfoSheet.vue';

let wrapper: VueWrapper | null = null;

function normalize(text: string | null | undefined): string {
  return (text ?? '').replace(/\s+/g, ' ').trim();
}

describe('InfoSheet copy', () => {
  afterEach(() => {
    wrapper?.unmount();
    wrapper = null;
  });

  it('renders the original Russian text', () => {
    wrapper = mount(InfoSheet, { props: { open: true }, attachTo: document.body });
    const text = normalize(document.body.querySelector('.info-sheet')?.textContent);
    const expected = [
      'Что это',
      'Bachata Roadmap — мобильное приложение с дорожной картой занятий: разминка, соло, элементы в паре и справочные блоки. Можно установить на экран «Домой» и пользоваться офлайн.',
      'Вкладки',
      '3 мес / 3–5 / 6+ — программа по этапам обучения',
      'Поиск — быстрый поиск элемента по названию или разделу',
      '📑 Элементы по блокам — сводный справочник по 5 модулям (в меню ☰)',
      'Чеклисты и прогресс',
      'Нажмите на элемент, чтобы отметить его выполненным',
      'Повторное нажатие снимает отметку',
      'Над списком — прогресс-бар по текущему периоду',
      'В заголовке секции — счётчик выполнено / всего',
      'Секции',
      'Нажмите на заголовок раздела (Разминка, Элементы в паре и т.д.), чтобы свернуть или развернуть список.',
      'Введите название фигуры или раздела. Нажмите на результат — приложение откроет нужную вкладку и период.',
      'Ученики и группы',
      'В меню ☰ — список учеников и групп, создание, справочник и сброс',
      'Ученики и группы — переключение, редактирование и удаление',
      'Новый ученик / группа — отдельный прогресс для каждого',
      'Имя задаёте сами — это может быть человек или название группы',
      'У каждого свой прогресс и своя последняя вкладка',
      'Сохранение',
      'Прогресс, список учеников и последняя вкладка сохраняются автоматически на устройстве',
      'После первого открытия приложение работает без интернета',
      'При каждом сохранении создаётся резервная копия на случай повреждения данных',
      'Обновление приложения не удаляет учеников и их прогресс',
      'Обновления',
      'При выходе новой версии приложение подтягивает её само при следующем открытии или возврате на вкладку. Страница может перезагрузиться один раз — это нормально. Ваши данные при этом сохраняются.',
      'Если что-то пошло не так',
      'Внизу экрана появляется короткое сообщение с объяснением',
      'Если данные повреждены — приложение попробует восстановить последнюю копию',
      'Если хранилище недоступно (режим инкогнито и т.п.) — прогресс не сохранится после перезагрузки',
      'Не хватает места на устройстве — освободите память в настройках браузера',
      'Установка на iPhone',
      'Откройте ссылку в Safari → Поделиться → «На экран «Домой»». Не открывайте из приложения «Файлы» — там PWA не работает.',
      'Сброс прогресса',
      'Кнопка ↺ в меню сбрасывает отметки только для текущего выбранного ученика или группы после подтверждения.',
    ];
    let cursor = 0;
    for (const part of expected) {
      const found = text.indexOf(part, cursor);
      expect(found, part).toBeGreaterThanOrEqual(0);
      cursor = found + part.length;
    }
  });
});
